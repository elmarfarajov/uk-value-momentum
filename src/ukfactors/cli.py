"""Command-line interface.

ukf data fetch                       download AQR, Exeter, FRED and Yahoo data into data/raw
ukf data list                        what is stored, with each file's SHA-256
ukf stats                            summary statistics of every UK factor, in sterling
ukf validate --out docs/VALIDATION.md
ukf gallery                          every chart in the documentation
"""

from __future__ import annotations

import argparse
import sys
import warnings
from datetime import datetime, timezone
from pathlib import Path


def cmd_data(args: argparse.Namespace) -> None:
    from .data import aqr, exeter, fred, store, yahoo

    if args.action == "fetch":
        aqr.fetch()
        exeter.fetch()
        fred.fetch()
        yahoo.fetch_constituents()
        yahoo.fetch_prices()
    entries = store.manifest()
    if not entries:
        print(f"nothing stored under {store.data_root()}; run `ukf data fetch`")
    for name, entry in sorted(entries.items()):
        print(f"{name:<32} {entry['fetched']}  sha256 {entry['sha256'][:16]}")


def cmd_stats(args: argparse.Namespace) -> None:
    from . import panel, stats

    warnings.filterwarnings("ignore")
    p = panel.build()
    cols = ["VAL", "MOM", "MKT", "SMB", "HML", "HML_DEVIL", "UMD", "QMJ", "EX_RMRF", "EX_SMB", "EX_HML", "EX_UMD"]
    table = stats.table(p[cols], reps=args.reps)
    shown = table[["start", "end", "months", "mean", "vol", "sharpe", "t_nw", "sharpe_lo", "sharpe_hi", "skew", "max_drawdown"]]
    print(shown.round(3).to_string())


def cmd_validate(args: argparse.Namespace) -> None:
    from .validation import run_validation, to_markdown

    warnings.filterwarnings("ignore")
    results = run_validation(fast=args.fast)
    table = to_markdown(results)
    print(table)
    if args.out:
        header = (
            "# Validation report\n\n"
            f"Generated by `ukf validate` on {datetime.now(timezone.utc):%Y-%m-%d}. Every statistic and data step is held to an "
            "independent method or a published number; checks that need the local raw data show SKIP where it is absent.\n\n"
        )
        Path(args.out).write_text(header + table + "\n", encoding="utf-8")
    if (results["status"] == "FAIL").any():
        sys.exit(1)


def cmd_gallery(args: argparse.Namespace) -> None:
    from . import gallery

    warnings.filterwarnings("ignore")
    written = gallery.build(args.out, only=args.only)
    if args.only is None:
        Path("docs").mkdir(exist_ok=True)
        Path("docs/GALLERY.md").write_text(gallery.markdown() + "\n", encoding="utf-8")
    print(f"{len(written)} charts written to {args.out}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="ukf", description="Value and momentum in the UK stock market, 1972-2026.")
    sub = parser.add_subparsers(dest="command", required=True)
    data = sub.add_parser("data", help="download the raw data, or list what is stored")
    data.add_argument("action", choices=["fetch", "list"])
    data.set_defaults(func=cmd_data)
    st = sub.add_parser("stats", help="summary statistics of every UK factor")
    st.add_argument("--reps", type=int, default=1000, help="bootstrap replications for the Sharpe intervals")
    st.set_defaults(func=cmd_stats)
    validate = sub.add_parser("validate", help="run the validation suite")
    validate.add_argument("--out", default=None)
    validate.add_argument("--fast", action="store_true")
    validate.set_defaults(func=cmd_validate)
    charts = sub.add_parser("gallery", help="redraw the documentation's charts")
    charts.add_argument("--out", default="docs/images")
    charts.add_argument("--only", default=None)
    charts.set_defaults(func=cmd_gallery)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
